"""Derive the portable-save compatibility allowlists from the recovered 1.9.1 tables (read only)."""
import argparse, hashlib, json
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument('tables', type=Path)
p.add_argument('--output', type=Path, default=Path('offline/java/local/kinja/BackupCatalog.java'))
a = p.parse_args()
sources = {}
def table(suffix):
    paths = list(a.tables.glob('*_' + suffix + '.json'))
    assert len(paths) == 1, (suffix, paths)
    data = paths[0].read_bytes()
    sources[paths[0].name] = hashlib.sha256(data).hexdigest()
    return json.loads(data.decode('utf-8-sig'))
regions = table('GameRegionCfgData')
items = table('ItemCfgData')
equips = table('EquipCfgCfgData')
qualities = table('EquipQualityCfgCfgData')
heroes = table('HeroCfgCfgData')
stars = table('HeroStarCfgCfgData')
talents = table('TalentCfgCfgData')
guides = table('PlayerGuideCfgCfgData')
hero_talents = table('HeroTalentCfgCfgData')
def ids(rows, key='id'): return ','.join(str(v) for v in sorted({x[key] for x in rows}))
text = '''package local.kinja;
// Generated by tools/metadata/build_backup_catalog.py from the exact APK 1.9.1 tables.
final class BackupCatalog {
    static boolean has(int[] values, long n) { return n <= Integer.MAX_VALUE && java.util.Arrays.binarySearch(values, (int)n) >= 0; }
'''
for name, rows in [('REGIONS', regions), ('ITEMS', items), ('HEROES', heroes), ('GUIDES', guides), ('HERO_TALENTS', hero_talents)]:
    text += '    static final int[] ' + name + ' = {' + ids(rows) + '};\n'
text += '    static final int[][] EQUIPS = {' + ','.join('{%d,%d}' % pair for pair in sorted({(x['id'],x['part']) for x in equips})) + '};\n'
text += '    static final int[][] QUALITY = {' + ','.join('{%d,%d}' % (x['quality'],x['level_limit']) for x in qualities) + '};\n'
text += '    static final int[][] HERO_STARS = {' + ','.join('{%d,%d,%d}' % (x['id'],x['star'],x['lv_limit']) for x in stars) + '};\n'
text += '    static final int TALENT_MAX = %d, EXTRA_MAX = %d;\n' % (sum(x['type']==0 for x in talents),sum(x['type']==1 for x in talents))
text += '}\n'
a.output.write_text(text, encoding='utf-8')
Path('offline/native/backup_regions.h').write_text('// Generated from the exact APK 1.9.1 GameRegion table.\nstatic constexpr int backup_region_ids[] = {' + ids(regions) + '};\n',encoding='utf-8')
a.output.with_suffix('.sources.json').write_text(json.dumps({'apk_sha256':'7953eb369ba9b8c814c4736dac4a7e3aa116a5583837f6f12d795ea70c20595e','tables_sha256':sources},indent=2)+'\n',encoding='utf-8')
print('Regions:',len(regions),'items:',len(items),'equipment:',len(equips),'heroes:',len(heroes),'star keys:',list(stars[0]))
